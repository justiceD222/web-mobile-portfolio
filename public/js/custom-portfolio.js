const grid = document.querySelector('[data-portfolio-grid]');
const tabs = document.querySelectorAll('[data-filter]');
const modal = document.querySelector('[data-modal]');
const modalTitle = document.querySelector('[data-modal-title]');
const modalCategory = document.querySelector('[data-modal-category]');
const modalDescription = document.querySelector('[data-modal-description]');
const modalTags = document.querySelector('[data-modal-tags]');
const modalGallery = document.querySelector('[data-modal-gallery]');
const nav = document.querySelector('[data-nav]');
const menuToggle = document.querySelector('[data-menu-toggle]');
let activeFilter = 'web';
function addText(parent, tag, className, text) { const el = document.createElement(tag); if (className) el.className = className; el.textContent = text; parent.appendChild(el); return el; }
function renderCover(parent, project) {
  if (project.cover.type === 'phone') {
    parent.classList.add('is-mobile-card');
    const backdrop = document.createElement('span');
    backdrop.className = 'phone-backdrop';
    backdrop.style.backgroundImage = 'url("' + project.cover.src + '")';
    const preview = document.createElement('span');
    preview.className = 'phone-preview';
    const img = document.createElement('img');
    img.src = project.cover.src;
    img.alt = project.cover.alt;
    img.loading = 'lazy';
    preview.appendChild(img);
    parent.appendChild(backdrop);
    parent.appendChild(preview);
    return;
  }
  const img = document.createElement('img');
  img.src = project.cover.src;
  img.alt = project.cover.alt;
  img.loading = 'lazy';
  parent.appendChild(img);
}
function renderPortfolio() {
  grid.innerHTML = '';
  projects.filter(function(project) { return project.category === activeFilter; }).forEach(function(project) {
    const card = document.createElement('button');
    card.type = 'button';
    card.className = 'project-card';
    card.dataset.project = project.id;
    card.setAttribute('aria-label', 'Open ' + project.title + ' details');
    renderCover(card, project);
    const content = document.createElement('span');
    content.className = 'project-card-content';
    addText(content, 'small', '', project.category);
    addText(content, 'h3', '', project.title);
    addText(content, 'p', '', project.summary);
    card.appendChild(content);
    grid.appendChild(card);
  });
}
function renderGallery(project) {
  modalGallery.innerHTML = '';
  modalGallery.className = 'detail-gallery is-' + project.galleryType;
  project.gallery.forEach(function(item) {
    const figure = document.createElement('figure');
    figure.className = 'gallery-item';
    const frame = document.createElement('div');
    frame.className = 'gallery-frame ' + project.galleryType;
    const img = document.createElement('img');
    img.src = item.src;
    img.alt = item.alt || project.title + ' ' + item.caption;
    img.loading = 'lazy';
    const figcaption = document.createElement('figcaption');
    figcaption.className = 'gallery-caption';
    figcaption.textContent = item.caption;
    frame.appendChild(img);
    figure.appendChild(frame);
    figure.appendChild(figcaption);
    modalGallery.appendChild(figure);
  });
}
function openProject(projectId) {
  const project = projects.find(function(item) { return item.id === projectId; });
  if (!project) return;
  modalTitle.textContent = project.title;
  modalCategory.textContent = project.category === 'web' ? 'Web Project' : 'Mobile Project';
  modalDescription.textContent = project.description;
  modalTags.innerHTML = '';
  project.tags.forEach(function(tag) { addText(modalTags, 'span', '', tag); });
  renderGallery(project);
  modal.classList.add('is-open');
  modal.setAttribute('aria-hidden', 'false');
  document.body.classList.add('no-scroll');
}
function closeModal() { modal.classList.remove('is-open'); modal.setAttribute('aria-hidden', 'true'); document.body.classList.remove('no-scroll'); }
tabs.forEach(function(tab) {
  tab.addEventListener('click', function() {
    activeFilter = tab.dataset.filter;
    tabs.forEach(function(item) { const isActive = item === tab; item.classList.toggle('is-active', isActive); item.setAttribute('aria-selected', String(isActive)); });
    renderPortfolio();
  });
});
grid.addEventListener('click', function(event) { const card = event.target.closest('[data-project]'); if (card) openProject(card.dataset.project); });
document.querySelectorAll('[data-close]').forEach(function(button) { button.addEventListener('click', closeModal); });
document.addEventListener('keydown', function(event) { if (event.key === 'Escape') closeModal(); });
menuToggle.addEventListener('click', function() { nav.classList.toggle('is-open'); });
nav.addEventListener('click', function() { nav.classList.remove('is-open'); });
renderPortfolio();
